static void s_mutate(unsigned char* data, int* size, int max_size)
{
	int n = *size;
	if (n <= 4) return;
	switch (s_rand_below(6)) {
	case 0: { // Bit flip.
		int i = (int)s_rand_below((uint32_t)n);
		data[i] ^= (unsigned char)(1u << s_rand_below(8));
		break;
	}
	case 1: { // Byte splice.
		int i = (int)s_rand_below((uint32_t)n);
		data[i] = (unsigned char)s_rand_below(256);
		break;
	}
	case 2: { // Marker damage: find a 0xFF and corrupt the code after it.
		int start = (int)s_rand_below((uint32_t)n - 1);
		for (int i = start; i < n - 1; ++i) {
			if (data[i] == 0xFF) { data[i + 1] = (unsigned char)s_rand_below(256); break; }
		}
		break;
	}
	case 3: { // Length-field damage: 16-bit big-endian value right after a marker.
		int start = (int)s_rand_below((uint32_t)n - 3);
		for (int i = start; i < n - 3; ++i) {
			if (data[i] == 0xFF && data[i + 1] >= 0xC0 && data[i + 1] != 0xD8 && data[i + 1] != 0xD9) {
				data[i + 2] = (unsigned char)s_rand_below(256);
				data[i + 3] = (unsigned char)s_rand_below(256);
				break;
			}
		}
		break;
	}
	case 4: { // Truncate.
		*size = 2 + (int)s_rand_below((uint32_t)n - 2);
		break;
	}
	case 5: { // Duplicate a random chunk over another spot (structure shuffling).
		int len = 1 + (int)s_rand_below(32);
		if (len > n / 2) len = n / 2;
		int src = (int)s_rand_below((uint32_t)(n - len));
		int dst = (int)s_rand_below((uint32_t)(n - len));
		memmove(data + dst, data + src, (size_t)len);
		break;
	}
	}
	(void)max_size;
}

int main(int argc, char* argv[])
{
	const unsigned char* seed = s_builtin_seed;
	int seed_size = (int)sizeof(s_builtin_seed);
	unsigned char* file_data = NULL;
	if (argc > 1) {
		FILE* fp = fopen(argv[1], "rb");
		if (!fp) { printf("Unable to open %s\n", argv[1]); return 1; }
		fseek(fp, 0, SEEK_END);
		long len = ftell(fp);
		fseek(fp, 0, SEEK_SET);
		file_data = (unsigned char*)malloc((size_t)len);
		if (fread(file_data, 1, (size_t)len, fp) != (size_t)len) { printf("Read failed\n"); return 1; }
		fclose(fp);
		seed = file_data;
		seed_size = (int)len;
	}
	int iterations = argc > 2 ? atoi(argv[2]) : 100000;
	uint64_t start_seed = argc > 3 ? (uint64_t)strtoull(argv[3], NULL, 10) : 1;

	unsigned char* buf = (unsigned char*)malloc((size_t)seed_size);
	int ok_count = 0, err_count = 0;
	for (int iter = 0; iter < iterations; ++iter) {
		s_rng_state = start_seed + (uint64_t)iter;
		memcpy(buf, seed, (size_t)seed_size);
		int size = seed_size;
		int mutations = 1 + (int)s_rand_below(4);
		for (int m = 0; m < mutations; ++m) s_mutate(buf, &size, seed_size);

		cj_image_t img = cj_load_jpg_mem(buf, size);
		if (img.pix) {
			++ok_count;
			CUTE_JPG_FREE(img.pix);
		} else {
			++err_count;
			if (!cj_error_reason) {
				printf("iter %d (seed %llu): NULL image with no error string\n",
					iter, (unsigned long long)(start_seed + (uint64_t)iter));
				return 1;
			}
		}
		if ((iter + 1) % 10000 == 0) {
			printf("%d iterations: %d decoded, %d rejected\n", iter + 1, ok_count, err_count);
		}
	}
	printf("Done. %d iterations: %d decoded, %d rejected, 0 crashes.\n", iterations, ok_count, err_count);
	free(buf);
	if (file_data) free(file_data);
	return 0;
}
