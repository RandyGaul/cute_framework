// Mutation fuzzer for cute_jpg.h, the sibling of cute_model_fuzz.c. JPEG is the classic
// hostile-input format -- decoder CVEs are a genre -- so the decoder must reject or
// gracefully degrade on arbitrary corruption, never read out of bounds. This harness takes
// a seed JPEG, applies deterministic random mutations (bit flips, byte splices, marker and
// length-field damage, truncation), and hands the result to cj_load_jpg_mem. Every run must
// end in either an image or a NULL + error string -- never a crash or hang.
//
// Deterministic by design: the PRNG is seeded from the command line, so any failure
// reproduces exactly. Build with a sanitizer to catch reads that stay inside the process
// but outside the buffer:
//
//     cl /TP /EHsc /fsanitize=address /Zi /Od /I libraries tools\cute_jpg_fuzz.c
//     cute_jpg_fuzz.exe <seed.jpg> [iterations] [start_seed]
//
// Without a seed file it fuzzes a tiny built-in baseline JPEG, so it runs anywhere.

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define CUTE_JPG_IMPLEMENTATION
#include <cute/cute_jpg.h>

// xorshift64*: tiny, deterministic, good enough to drive mutations.
static uint64_t s_rng_state;
static uint32_t s_rand(void)
{
	uint64_t x = s_rng_state;
	x ^= x >> 12; x ^= x << 25; x ^= x >> 27;
	s_rng_state = x;
	return (uint32_t)((x * 0x2545F4914F6CDD1DULL) >> 32);
}
static uint32_t s_rand_below(uint32_t n) { return n ? s_rand() % n : 0; }

